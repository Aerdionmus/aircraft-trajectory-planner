"""T-1, T-2: Milestone 1 behaviour is preserved bit-for-bit with ``turn_model="none"``.

``tests/data/milestone1_parity.csv`` was generated by running
``configs/experiment_parity.json`` against commit ``76e9c54`` -- i.e. by the
Milestone 1 code, before any of this milestone existed.  Every deterministic
column it contains must still reproduce exactly.  Milestone 2 adds columns; the
comparison is over the intersection, so new metrics are allowed but no old
number may move.
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

import pytest

from atp.experiments.runner import (
    NON_DETERMINISTIC_COLUMNS,
    ExperimentSpec,
    run_matrix,
)
from atp.planning.cost import CostModel, CostWeights
from atp.scenarios.library import SCENARIO_LIBRARY, get_scenario
from atp.scenarios.spec import build_scenario

GOLDEN = Path(__file__).parent / "data" / "milestone1_parity.csv"
CONFIG = Path(__file__).parent.parent / "configs" / "experiment_parity.json"

#: Columns that exist in the golden file but are structurally new in Milestone 2
#: (the run identity gained a turn_model field); excluded from the value compare.
_IGNORED = NON_DETERMINISTIC_COLUMNS | {"turn_model"}


def _load_golden() -> list[dict[str, str]]:
    with GOLDEN.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _comparable(value: str) -> object:
    try:
        number = float(value)
    except ValueError:
        return value
    return number


def test_golden_file_is_present_and_nonempty():
    rows = _load_golden()
    assert len(rows) == 80
    assert rows[0]["scenario"] == "empty-cruise"


def test_milestone1_matrix_reproduces_the_golden_results_exactly():
    spec = ExperimentSpec.load(CONFIG)
    reports = run_matrix(spec)
    golden = _load_golden()
    assert len(reports) == len(golden)

    shared = [c for c in golden[0] if c not in _IGNORED]
    assert "comparable_cost" in shared and "expansions" in shared

    for report, expected in zip(reports, golden):
        row = report.as_row()
        for column in shared:
            raw = row.get(column, "")
            got = _comparable("" if raw is None else str(raw))
            want = _comparable(expected[column])
            context = f"{expected['scenario']}/{expected['heuristic']}:{column}"
            if isinstance(want, float) and isinstance(got, float):
                if math.isinf(want) or math.isinf(got):
                    assert got == want, context
                else:
                    assert got == pytest.approx(want, rel=1e-12, abs=1e-12), context
            else:
                assert str(got) == str(want), context


@pytest.mark.parametrize("name", sorted(SCENARIO_LIBRARY))
def test_heuristic_bounds_are_untouched_by_milestone_2(name):
    """T-2: the two quantities the admissible heuristic is built from must be
    identical whether or not turns are modelled -- they bound cost per NM of
    *horizontal* progress, and a turn adds no horizontal progress."""
    spec = get_scenario(name)
    built = build_scenario(spec)
    weights: CostWeights = built.cost_model.weights
    without = CostModel(built.airspace, built.aircraft, weights, turn_model="none")
    with_turns = CostModel(
        built.airspace, built.aircraft, weights, turn_model="gate+cost"
    )
    assert with_turns.speed_cost_lower_bound_per_nm() == (
        without.speed_cost_lower_bound_per_nm()
    )
    assert with_turns.constant_cost_offset() == without.constant_cost_offset()


def test_library_scenarios_default_to_milestone_1_semantics():
    """Only scenarios that explicitly opt in use turn dynamics; everything else
    must still be Milestone 1.

    ``turn-limited-wind`` was added to give the wind-aware air-heading machinery
    experimental coverage. ``turn-limited-fixed-speed`` and the four Milestone 3
    speed scenarios also opt in -- a speed decision is only meaningful with turn
    dynamics enabled, since it is the turn model that makes speed change
    anything about feasibility. None of these six is in
    ``configs/experiment_parity.json``, so the golden Milestone 1 matrix above is
    untouched by any of them; this assertion stays an exact set equality so that
    a further scenario cannot quietly opt into turn dynamics.
    """
    opted_in = {
        name for name in SCENARIO_LIBRARY if get_scenario(name).turn_model != "none"
    }
    assert opted_in == {
        "turn-limited",
        "turn-limited-wind",
        "turn-limited-fixed-speed",
        "speed-choice",
        "speed-choice-min-time",
        "speed-choice-min-fuel",
        "speed-turn-frontier",
    }
